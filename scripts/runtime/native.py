"""Isolate pinned emulator state and serialize handle-owned native runs."""

import os
from pathlib import Path
import platform
import re
import shutil
import subprocess
import time

from scripts.build.project import ROOT, atomic, load, rltool, sha
from scripts.runtime.processes import owned_leftovers, processes, remember_owned, terminate_owned


def validate_executable(data, expected):
    if len(data) != expected["size"] or sha(data) != expected["sha256"]:
        raise ValueError("MAME executable differs from the pinned build")


def prepare(named=None):
    spec = load("config/runtime/emulator.json")
    host = "windows-x86_64" if os.name == "nt" and platform.machine().lower() in ("amd64", "x86_64") else "unsupported"
    if host not in spec["hosts"]:
        raise ValueError("Full runtime is not accepted on this host; ROM-less checks remain available")
    target = ROOT / "build/runtime/mame/consoles.exe"
    expected = spec["hosts"][host]
    if target.is_file():
        validate_executable(target.read_bytes(), expected)
        return target
    source = Path(named or os.environ.get("RETROLARIUM_MAME") or rltool("movie", "mame"))
    if not source.is_file():
        raise ValueError("Name the pinned MAME through --mame or RETROLARIUM_MAME")
    data = source.read_bytes()
    validate_executable(data, expected)
    atomic(target, data)
    return target


def active_processes():
    return [row["pid"] for row in processes()]


def wait_idle(timeout):
    started = time.monotonic()
    reported = -1
    while True:
        pids = active_processes()
        if not pids:
            return
        elapsed = int(time.monotonic() - started)
        if elapsed // 30 != reported:
            print("[WAIT] Existing MAME process(es): " + ", ".join(map(str, pids)), flush=True)
            reported = elapsed // 30
        if elapsed >= timeout:
            raise RuntimeError("MAME stayed busy; no second run was started")
        time.sleep(1)


def reset_emulator(mame):
    stage = ROOT / "build/runtime/mame"
    resolved = stage.resolve()
    if (
        resolved != stage.absolute()
        or not resolved.is_relative_to((ROOT / "build").resolve())
        or mame.is_symlink()
        or mame.resolve() != resolved / "consoles.exe"
    ):
        raise ValueError("MAME state cleanup leaves its exact isolated build directory")
    children = [path for path in stage.iterdir() if path.name != "consoles.exe"]
    # Preflight the entire deletion set before removing even its first entry.
    for path in children:
        target = path.resolve()
        if path.is_symlink() or target == resolved or not target.is_relative_to(resolved):
            raise ValueError("MAME state cleanup encountered an escaping path")
    for path in children:
        if path.is_dir():
            shutil.rmtree(path)
        else:
            path.unlink()


def nvram_path(args):
    """Name only the cartridge state generated by this explicit movie invocation."""
    try:
        rom = Path(args[args.index("--rom") + 1])
        spec = load(str(Path(args[1]).resolve().relative_to(ROOT)))
    except (ValueError, IndexError, TypeError) as error:
        raise ValueError("NVRAM needs an explicit project movie check and cartridge") from error
    machine = spec.get("machine")
    if machine not in ("genesis", "megadriv", "megadrij") or not re.fullmatch("[a-z0-9][a-z0-9_-]*", rom.stem):
        raise ValueError("Invalid machine or cartridge identity for NVRAM")
    return ROOT / "build/runtime/mame/nvram" / machine / (rom.stem + ".nv")


def validate_nvram(data):
    if not isinstance(data, bytes) or not 0 < len(data) <= 131072:
        raise ValueError("NVRAM must be a bounded cartridge byte snapshot")


def read_nvram(args):
    path = nvram_path(args)
    if not path.is_file() or path.is_symlink() or path.resolve() != path.absolute():
        raise ValueError("Movie did not produce its own isolated cartridge NVRAM")
    data = path.read_bytes()
    validate_nvram(data)
    return data


def run_movie(args, log, *, nvram=None):
    from scripts.build.project import rltool_command

    spec = load("config/runtime/emulator.json")
    wait_idle(spec["busy_timeout_seconds"])
    try:
        position = args.index("--mame")
        mame = Path(args[position + 1])
    except (ValueError, IndexError) as error:
        raise ValueError("Runtime must name the isolated emulator explicitly") from error
    # Validate the entire explicit seed before discarding any previous state.
    seed_path = None
    if nvram is not None:
        validate_nvram(nvram)
        seed_path = nvram_path(args)
    reset_emulator(mame)
    if seed_path is not None:
        atomic(seed_path, nvram)
    temporary = ROOT / "build/runtime/tmp"
    temporary.mkdir(parents=True, exist_ok=True)
    env = dict(os.environ, PYTHONDONTWRITEBYTECODE="1", TEMP=str(temporary), TMP=str(temporary), TMPDIR=str(temporary))
    log.parent.mkdir(parents=True, exist_ok=True)
    proc, owned = None, {}
    try:
        with log.open("w", encoding="utf-8") as stream:
            proc = subprocess.Popen(
                [*rltool_command(), "movie", *map(str, args)],
                cwd=ROOT,
                env=env,
                stdout=stream,
                stderr=subprocess.STDOUT,
                creationflags=0x08000000 if os.name == "nt" else 0,
            )
            deadline = time.monotonic() + spec["run_timeout_seconds"]
            while True:
                remember_owned(processes(), proc.pid, owned)
                remaining = deadline - time.monotonic()
                if remaining <= 0:
                    raise subprocess.TimeoutExpired(proc.args, spec["run_timeout_seconds"])
                try:
                    code = proc.wait(timeout=min(0.2, remaining))
                    break
                except subprocess.TimeoutExpired:
                    if time.monotonic() >= deadline:
                        raise
    except subprocess.TimeoutExpired as error:
        if proc is not None and proc.poll() is None:
            proc.kill()
            proc.wait(timeout=5)
        raise RuntimeError("Owned MAME runner exceeded its frame/run budget") from error
    finally:
        try:
            if proc is not None and proc.poll() is None:
                proc.kill()
                proc.wait(timeout=5)
        finally:
            rows = processes()
            if proc is not None:
                remember_owned(rows, proc.pid, owned)
            leftovers = owned_leftovers(rows, owned)
            for row in leftovers:
                terminate_owned(row["pid"], row["created"])
            if leftovers:
                foreign = [row["pid"] for row in rows if row not in leftovers]
                raise RuntimeError(
                    "MAME remained after the run; owned cleanup attempted for "
                    + str([row["pid"] for row in leftovers])
                    + "; unrelated processes preserved: "
                    + str(foreign)
                )
    if code:
        raise RuntimeError(log.read_text(encoding="utf-8", errors="replace")[-3000:])
